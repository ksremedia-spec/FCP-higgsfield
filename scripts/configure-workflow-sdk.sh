#!/bin/bash
# Locates Apple's Workflow Extension SDK (ProExtensionHost.framework) and writes
# App/Config/ProExtensionHost.local.xcconfig so the extension links and embeds it.
# Usage: scripts/configure-workflow-sdk.sh [/path/to/ProExtensionHost.framework]
set -euo pipefail
cd "$(dirname "$0")/.."

framework="${1:-}"
if [ -z "$framework" ]; then
  for candidate in \
    /Library/Frameworks/ProExtensionHost.framework \
    /Library/Developer/Frameworks/ProExtensionHost.framework \
    "$HOME/Library/Frameworks/ProExtensionHost.framework"; do
    if [ -d "$candidate" ]; then framework="$candidate"; break; fi
  done
fi
if [ -z "$framework" ]; then
  framework=$(find /Library /Applications/Xcode.app/Contents/Developer -maxdepth 6 -name ProExtensionHost.framework -type d 2>/dev/null | head -1 || true)
fi
if [ -z "$framework" ] || [ ! -d "$framework" ]; then
  echo "ProExtensionHost.framework not found. Install the Workflow Extension SDK from" >&2
  echo "https://developer.apple.com/download/all/?q=WorkflowExtensions or pass its path." >&2
  exit 1
fi

dir=$(dirname "$framework")
out=App/Config/ProExtensionHost.local.xcconfig
cat > "$out" <<XC
// Generated by scripts/configure-workflow-sdk.sh — machine-specific, not committed.
PRO_EXTENSION_HOST_FRAMEWORK = $framework
FRAMEWORK_SEARCH_PATHS = \$(inherited) $dir
OTHER_LDFLAGS = \$(inherited) -weak_framework ProExtensionHost
XC
echo "Configured $out with $framework"
