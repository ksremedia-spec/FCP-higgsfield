#!/usr/bin/env python3
"""Generate Sources/HiggsfieldKit/Operations/CatalogSnapshot.swift.

Converts the captured Higgsfield catalog entries in
tools/catalog-snapshot-2026-10-26.json into JSON Schema documents shaped like
the `json_schema` the account API returns from GET /job_types/{job_type}.
The snapshot is only a fallback used when the live catalog can't be fetched.

Usage: python3 tools/generate_catalog_snapshot.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "catalog-snapshot-2026-10-26.json"
DST = ROOT / "Sources" / "HiggsfieldKit" / "Operations" / "CatalogSnapshot.swift"


def param_schema(p):
    s = {}
    if p.get("description"):
        s["description"] = p["description"]
    if "options" in p:
        s["enum"] = p["options"]
    elif p.get("type") == "bool":
        s["type"] = "boolean"
    elif p.get("type") == "number":
        s["type"] = "number"
        if "min" in p:
            s["minimum"] = p["min"]
        if "max" in p:
            s["maximum"] = p["max"]
    else:
        s["type"] = "string"
    if "default" in p:
        s["default"] = p["default"]
    return s


# Utility job types that take no prompt (per the MCP tool descriptions:
# "This tool does not use prompt or count").
NO_PROMPT = {
    "reframe", "video_background_remover", "image_background_remover",
    "topaz_video", "bytedance_video_upscale", "bytedance_image_upscale",
}


def model_schema(m, overrides):
    props = {} if m["id"] in NO_PROMPT else {"prompt": {"type": "string"}}
    for p in m.get("parameters") or []:
        if p.get("type") == "string_array":
            continue
        props[p["name"]] = param_schema(p)
    if m.get("aspect_ratios"):
        props["aspect_ratio"] = {"enum": m["aspect_ratios"], "default": m["aspect_ratios"][0]}
    rng = m.get("duration_range")
    if rng and "duration" not in props:
        props["duration"] = {"type": "number", "minimum": rng["min"], "maximum": rng["max"], "default": rng["min"]}
    roles = []
    for media in m.get("medias") or []:
        roles += media.get("roles") or []
    roles = overrides.get(m["id"], {}).get("roles", roles)
    if roles:
        props["medias"] = {
            "type": "array",
            "items": {"type": "object", "properties": {"role": {"enum": roles}, "data": {"type": "object"}}},
        }
    return {"type": "object", "properties": props}


def main():
    data = json.loads(SRC.read_text())
    entries = []
    for m in data["models"]:
        entries.append({
            "job_type": m["id"],
            "name": m["name"],
            "provider": m.get("provider_name") or "",
            "type": m["output_type"],
            "json_schema": model_schema(m, data.get("overrides", {})),
        })
    payload = json.dumps(entries, indent=1, sort_keys=True, ensure_ascii=False)
    DST.write_text(
        "// Generated by tools/generate_catalog_snapshot.py — do not edit by hand.\n"
        f"// Source: {data['source']}\n"
        f"// Captured: {data['captured']}\n\n"
        "import Foundation\n\n"
        "enum CatalogSnapshot {\n"
        f"    static let captured = \"{data['captured']}\"\n\n"
        "    static let json = #\"\"\"\n"
        f"{payload}\n"
        "\"\"\"#\n"
        "}\n"
    )
    print(f"wrote {DST.relative_to(ROOT)} ({len(entries)} job types)")


if __name__ == "__main__":
    main()
