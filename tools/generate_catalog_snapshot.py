#!/usr/bin/env python3
"""Generate Sources/HiggsfieldKit/Operations/CatalogSnapshot.swift.

tools/catalog-snapshot-2026-10-26.json holds the live responses of
GET /job_types/{job_type} for every model the panel offers, so the bundled
fallback is exactly what the panel reads at run time. The snapshot is only
used when the live catalog can't be fetched.

To refresh the source file (free, read-only calls), with a valid session:

    T=$(hf auth token); W=<workspace id>
    curl -s -H "Authorization: Bearer $T" -H "hf-workspace-id: $W" \
      https://fnf-api-gw.higgsfield.ai/fnf/developer/v2alpha/job_types/<job_type>

and keep the fields job_type, display_name, provider, type and json_schema.

Usage: python3 tools/generate_catalog_snapshot.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "catalog-snapshot-2026-10-26.json"
DST = ROOT / "Sources" / "HiggsfieldKit" / "Operations" / "CatalogSnapshot.swift"


def main():
    data = json.loads(SRC.read_text())
    entries = []
    for m in data["models"]:
        entries.append({
            "job_type": m["job_type"],
            "name": m.get("display_name") or m["job_type"],
            "provider": m.get("provider") or "",
            "type": m["type"],
            "json_schema": m["json_schema"],
        })
    entries.sort(key=lambda e: e["job_type"])
    payload = json.dumps(entries, indent=1, sort_keys=True, ensure_ascii=False)
    if '"""#' in payload:
        raise SystemExit("snapshot contains the Swift raw-string terminator")
    DST.write_text(
        "// Generated by tools/generate_catalog_snapshot.py — do not edit by hand.\n"
        f"// Source: {data['source']}\n"
        f"// Captured: {data['captured']}\n\n"
        "import Foundation\n\n"
        "enum CatalogSnapshot {\n"
        f"    static let captured = \"{data['captured']}\"\n\n"
        "    static let json = #\"\"\"\n"
        f"{payload}\n"
        "\"\"\"#\n"
        "}\n"
    )
    print(f"wrote {DST.relative_to(ROOT)} ({len(entries)} job types)")


if __name__ == "__main__":
    main()
